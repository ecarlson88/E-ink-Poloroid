"""Draw the setup-mode screen (Task 5 Step 3) and write firmware/magnet/setup_screen.h.

The magnet shows this when it cannot reach Wi-Fi (third failed wake) or when setup is started
by hand. Ruling: the screen is shared by all case types, so it only explains how to join;
how to start setup again goes on each case's printed card (docs/setup-card.md).

The text is drawn as a 480 x 640 (3:4) picture and packed through the server's render_frame,
so it lands in the part of the panel the case shows, with the same nibble order and
orientation as the photos. Run from the repo root:
    python tools/make_setup_screen.py
and re-run it whenever HIGH_NIBBLE_IS_LEFT or PICTURE_ROWS_FIRST change in server/imaging.py."""
import io
import sys
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "server"))
import imaging  # noqa: E402

NETWORK = "FridgeMagnet-Setup"
FRAME_BYTES = 172_800


def _font(size: int) -> ImageFont.ImageFont:
    return ImageFont.load_default(size=size)


def _wifi_icon(d: ImageDraw.ImageDraw, cx: int, cy: int) -> None:
    for r in (70, 50, 30):
        d.arc((cx - r, cy - r, cx + r, cy + r), start=225, end=315, fill=0, width=9)
    d.ellipse((cx - 9, cy - 9, cx + 9, cy + 9), fill=0)


def setup_screen_image() -> Image.Image:
    """The picture as it should look: black on white, 480 x 640."""
    img = Image.new("1", (imaging.PICTURE_W, imaging.PICTURE_H), 1)
    d = ImageDraw.Draw(img)
    d.fontmode = "1"                          # no anti-aliasing, so no dithered grey edges
    cx = imaging.PICTURE_W // 2
    _wifi_icon(d, cx, 120)

    def centred(y, text, size, stroke=0):
        d.text((cx, y), text, fill=0, font=_font(size), anchor="mt", stroke_width=stroke, stroke_fill=0)

    centred(150, "Wi-Fi setup", 46, stroke=1)
    centred(240, "1. On your phone, join", 30)
    centred(278, "this Wi-Fi network:", 30)
    d.rounded_rectangle((28, 324, imaging.PICTURE_W - 28, 400), radius=14, outline=0, width=4)
    centred(344, NETWORK, 34, stroke=1)
    centred(440, "2. Then open the page", 30)
    centred(478, "that appears.", 30)
    centred(560, "(No page? Open any website.)", 22)
    return img


def setup_screen_frame() -> bytes:
    buf = io.BytesIO()
    setup_screen_image().convert("RGB").save(buf, format="PNG")
    frame = imaging.render_frame(buf.getvalue())
    assert len(frame) == FRAME_BYTES
    return frame


def write_header(path: Path) -> None:
    frame = setup_screen_frame()
    rows = [", ".join(f"0x{b:02X}" for b in frame[i:i + 24]) for i in range(0, len(frame), 24)]
    path.write_text(
        "/* Generated by tools/make_setup_screen.py; do not edit. The setup-mode screen as one\n"
        " * packed panel frame (480 x 720, 4 bits per pixel), drawn by setup mode (Task 5). */\n"
        "#pragma once\n#include <stdint.h>\n\n"
        f"static const uint8_t setup_screen_frame[{len(frame)}] = {{\n  " + ",\n  ".join(rows) + "\n};\n")


def main() -> None:
    out = ROOT / "firmware" / "magnet" / "setup_screen.h"
    write_header(out)
    imaging.frame_to_image(setup_screen_frame()).save(ROOT / "firmware" / "magnet" / "setup_screen.png")
    print(f"wrote {out}", file=sys.stderr)


if __name__ == "__main__":
    main()
